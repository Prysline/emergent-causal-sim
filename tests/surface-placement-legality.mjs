// B1: pure geometry and actual canonical runtime/authoring consumers.
import assert from 'node:assert/strict';
import {loadProductionBefore,loadScriptsInThisContext} from './helpers/production-loader.mjs';
globalThis.window=globalThis;
loadProductionBefore('src/ui/core.js');
const A=SimWorldAuthoring,L=SimSurfacePlacement,SP=SimSpatial,E=SimEngine,V=SimValidator;
assert.equal(SP.NEARBY_PLACEMENT_VERSION,'nearby-placement-v5-intentional-approach');
E.reset(20261126);
const st=E.getState(),counter=st.furniture.counterA,node=SP.normalizeNode(st,counter.spatial.surfaces[0].cells[0],counter.spatial.surfaces[0].id);
const item={id:'probe',placementFootprint:{width:.3,depth:.3}};
const region=L.placementCellRegion(counter,node);
assert.ok(Math.abs(region.area-.7056)<1e-9);
assert.equal(L.surfacePlacementStatus({},counter,node,item).ok,true);
assert.equal(L.surfacePlacementStatus({invalid:null},counter,node,item).reason,'invalid-object-record');
assert.equal(L.surfacePlacementStatus({},counter,node,{id:'missing',handling:{carryGeometry:{width:.1,length:.1}}}).reason,'invalid-placement-footprint');
assert.equal(L.surfacePlacementStatus({},counter,node,{id:'oversize',placementFootprint:{width:.85,depth:.1}}).ok,false);
const cargo={};
for(let i=0;i<7;i++)cargo['p'+i]={id:'p'+i,supportId:counter.id,position:node,placementFootprint:{width:.3,depth:.3}};
assert.equal(L.surfacePlacementStatus(cargo,counter,node,item).reason,'surface-area-exceeded');
delete cargo.p0;
assert.equal(L.surfacePlacementStatus(cargo,counter,node,item).ok,true);
cargo.child={id:'child',containedBy:'p1'};
cargo.upper={id:'upper',supportId:counter.id,position:{...node,z:1},placementFootprint:{width:.8,depth:.8}};
assert.equal(L.surfacePlacementStatus(cargo,counter,node,item).ok,true,'contained or different-layer objects do not consume surface');
const doc=A.cloneAuthoring(A.DEFAULT_WORLD_AUTHORING);
assert.equal(A.validateAuthoring(doc).ok,true);
for(const invalid of [null,[],false]){
  const malformed=A.cloneAuthoring(doc);
  malformed.entities.objects.invalid=invalid;
  const report=A.validateAuthoring(malformed);
  assert.equal(report.ok,false,'malformed Object records must be rejected by validation, not throw');
  assert.ok(report.errors.some(x=>x.code==='authoring_object_invalid'));
}
delete doc.entities.objects.plateA.placementFootprint;
assert.ok(A.validateAuthoring(doc).errors.some(x=>x.code==='authoring_object_placement_footprint_required'));
const full=A.cloneAuthoring(A.DEFAULT_WORLD_AUTHORING);
full.entities.objects.blocker={id:'blocker',name:'capacity witness',portable:false,position:{x:11,y:2,z:0},supportId:'counterA',placementFootprint:{width:.84,depth:.84}};
assert.ok(A.validateAuthoring(full).errors.some(x=>x.code==='authoring_object_surface_placement_invalid'));
loadScriptsInThisContext(['src/editor-authoring-mutations.js','src/editor-ordinary-object-authoring.js']);
const edit=A.cloneAuthoring(A.DEFAULT_WORLD_AUTHORING);
delete edit.entities.objects.ingredientA1;
edit.entities.objects.blocker=full.entities.objects.blocker;
assert.equal(A.validateAuthoring(edit).ok,true);
const before=A.semanticFingerprint(edit);
const rejected=SimEditorAuthoringMutations.createOrdinaryObjectFromTemplate(edit,{templateId:'readable-book',target:{x:11,y:2,z:0},supportChoice:{kind:'furniture',furnitureId:'counterA'}});
assert.equal(rejected.ok,false);
assert.ok(rejected.issues.some(x=>x.code==='authoring_object_surface_placement_invalid'));
assert.equal(A.semanticFingerprint(edit),before,'rejection is atomic');
const a=st.agents.zhen,held=st.objects.ingredientA1;
a.position={...SP.supportContactNodes(st,counter.id,a)[0]};
a.held=held.id;delete held.supportId;delete held.containedBy;
st.objects.blocker={...full.entities.objects.blocker,position:{...node}};
assert.equal(SP.releaseHeldObjectOnSupport(st,a,counter.id),null);
assert.equal(a.held,held.id);
delete st.objects.blocker;
const result=SP.releaseHeldObjectOnSupport(st,a,counter.id);
assert.equal(result?.supportId,counter.id);
assert.equal(a.held,null);
assert.equal(held.supportId,counter.id);
assert.equal(V.validateState(st).issues.some(x=>x.code==='object_surface_placement_invalid'),false);
held.placementFootprint={width:2,depth:2};
assert.equal(V.validateState(st).issues.some(x=>x.code==='object_surface_placement_invalid'),true);
// Generic intentional release uses the same object-specific rule, not a separate capacity answer.
// An oversized object is legal on Floor but fits none of the nearby support cells.
a.held=held.id;delete held.supportId;
assert.equal(SP.bestNearbySupportPlacement(st,a),null,'no support can fit the oversized held Object');
const floor=SP.normalizeNode(st,a.position,'floor');
const fallback=SP.releaseHeldObjectNearby(st,a);
assert.equal(fallback?.kind,'floor');
assert.equal(a.held,null);
assert.equal(held.supportId,undefined);
assert.ok(SP.nodeSame(st,SP.objectNode(st,held.id),floor));
assert.equal(V.validateState(st).issues.some(x=>x.code==='object_surface_placement_invalid'),false);
held.placementFootprint={width:.12,depth:.12};
a.held=held.id;
const winner=SP.bestNearbySupportPlacement(st,a);
assert.ok(winner,'a small held Object can use a legal nearby support');
const ordinary=SP.releaseHeldObjectNearby(st,a);
assert.equal(ordinary?.supportId,winner.supportId);
assert.ok(SP.nodeSame(st,ordinary.node,winner.node));
assert.equal(a.held,null);
console.log('B1 Surface Placement geometry, authoring/editor, targeted and generic release: ok');
